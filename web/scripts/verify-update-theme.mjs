import { chromium, expect } from '@playwright/test';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { AesEncrypt } from '../src/utils/legacyCipher.ts';

const origin = process.env.OVERVIEW_TEST_ORIGIN || 'http://127.0.0.1:3001';
const output = new URL('../../artifacts/', import.meta.url);
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, colorScheme: 'light' });
const report = { checks: [], errors: [] };
let updateAvailable = false;
await context.addInitScript(() => {
  localStorage.setItem('access_token', 'isolated-theme-verification');
  if (!localStorage.getItem('lang')) localStorage.setItem('lang', 'zh_CN');
});
await context.routeWebSocket('**/api/**', (ws) => ws.close());
await context.route('**/api/**', async (route) => {
  const path = new URL(route.request().url()).pathname;
  if (path.includes('handshake') || path.endsWith('/public/seckey')) return route.fulfill({ json: { code: 1, msg: 'Isolated legacy transport test' } });
  let data = { list: [], total: 0 }, msg = 'OK';
  if (path.endsWith('/sysinfo/checkversion')) {
    data = { need_update: updateAvailable, version: 'v2.0.0-dev', version_new: updateAvailable ? 'v2.0.1' : '', version_desc: 'Release verification', self_update_allowed: true };
    msg = updateAvailable ? '有新版本' : 'HomeWaf 更新源尚未发布正式版本，发布后即可检查更新';
  }
  if (path.endsWith('/systemconfig/list')) data = { list: [], total: 0 };
  return route.fulfill({ json: { code: 0, data: AesEncrypt(JSON.stringify(data)), msg } });
});
const page = await context.newPage();
page.on('pageerror', (error) => report.errors.push(error.message));
const drawer = page.locator('.setting-drawer-container');
const openSettings = async () => {
  await page.getByRole('button', { name: /^(系统设置|System Settings|System Config)$/i }).click();
  await expect(drawer).toBeVisible();
};
const closeSettings = async () => {
  await drawer.locator('.el-drawer__close-btn').click();
  await expect(drawer).toBeHidden();
};
const chooseMode = async (mode) => drawer.locator(`.setting-theme-modes label:has(input[value="${mode}"])`).click();
const primary = () => page.locator('html').evaluate((el) => getComputedStyle(el).getPropertyValue('--el-color-primary').trim().toLowerCase());
try {
  await page.goto(origin + '/#/sys/SystemConfig');
  await expect(page.locator('.config-layout')).toBeVisible({ timeout: 20000 });
  await openSettings();
  await chooseMode('light');
  for (const [name, color] of [['cyan', '#0594fa'], ['green', '#00a870'], ['yellow', '#ebb105'], ['orange', '#ed7b2f'], ['red', '#e34d59'], ['pink', '#ed49b4'], ['purple', '#834ec2'], ['default', '#0052d9']]) {
    await drawer.locator(`.setting-theme-colors label:has(input[value="${name}"])`).click();
    await expect.poll(primary).toBe(color);
    await expect(drawer.locator('.el-tabs__active-bar')).toHaveCSS('background-color', `rgb(${[1, 3, 5].map((i) => parseInt(color.slice(i, i + 2), 16)).join(', ')})`);
    await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('samwaf_page_setting')).brandTheme)).toBe(name);
  }
  report.checks.push('All eight preset colors update rendered controls and persisted settings');
  const customButton = drawer.locator('.dynamic-color-btn');
  await customButton.click();
  const picker = page.locator('.theme-color-popup');
  await expect(picker).toBeVisible();
  await expect(picker).toHaveCSS('opacity', '1');
  await expect(picker).toHaveCSS('background-color', 'rgb(255, 255, 255)');
  await expect(picker.locator('.el-color-picker-panel')).toBeVisible();
  await picker.locator('.el-color-svpanel').click({ position: { x: 80, y: 70 } });
  const rgb = picker.locator('input');
  await expect(rgb).toHaveValue(/^rgb\(/);
  await rgb.fill('rgb(18, 123, 207)');
  await rgb.press('Tab');
  await expect.poll(primary).toBe('#127bcf');
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('samwaf_page_setting')).brandTheme)).toBe('#127bcf');
  await page.screenshot({ path: fileURLToPath(new URL('theme-color-rgb-light.png', output)) });
  await picker.getByRole('button', { name: '完成' }).click();
  await expect(picker).toBeHidden();
  await customButton.focus();
  await customButton.press('Enter');
  await expect(picker).toBeVisible();
  await drawer.locator('.setting-group-title').first().click();
  await expect(picker).toBeHidden();
  await chooseMode('dark');
  await expect(page.locator('html')).toHaveClass(/dark/);
  await expect.poll(primary).toBe('#127bcf');
  await customButton.click();
  await expect(picker).toBeVisible();
  await expect(picker).toHaveCSS('opacity', '1');
  await page.screenshot({ path: fileURLToPath(new URL('theme-color-rgb-dark.png', output)) });
  await closeSettings();
  await expect(picker).toBeHidden();
  await page.reload();
  await expect(page.locator('.config-layout')).toBeVisible();
  await expect.poll(primary).toBe('#127bcf');
  await openSettings();
  await expect(customButton).toHaveClass(/is-active/);
  await customButton.click();
  await expect(rgb).toHaveValue('rgb(18, 123, 207)');
  await picker.getByRole('button', { name: '完成' }).click();
  await drawer.locator('.setting-theme-colors label:has(input[value="green"])').click();
  await chooseMode('auto');
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect.poll(primary).toBe('#03a56f');
  await page.emulateMedia({ colorScheme: 'light' });
  await expect.poll(primary).toBe('#00a870');
  await page.setViewportSize({ width: 390, height: 1000 });
  await customButton.click();
  await expect(picker).toBeVisible();
  await expect(picker).toHaveCSS('opacity', '1');
  const frame = await picker.boundingBox();
  expect(frame.x).toBeGreaterThanOrEqual(0);
  expect(frame.x + frame.width).toBeLessThanOrEqual(391);
  await page.screenshot({ path: fileURLToPath(new URL('theme-color-rgb-mobile.png', output)) });
  await picker.getByRole('button', { name: '完成' }).click();
  report.checks.push('RGB panel opens with mouse/keyboard, applies color, closes outside/drawer, persists after reload, and fits mobile');
  await closeSettings();
  await page.setViewportSize({ width: 1440, height: 1000 });
  const toggle = page.locator('.sidebar-toggle');
  await expect(toggle.locator('[data-icon="Fold"]')).toBeVisible();
  await expect(toggle).toHaveAttribute('aria-expanded', 'true');
  await toggle.click();
  await expect(toggle.locator('[data-icon="Expand"]')).toBeVisible();
  await expect(toggle).toHaveAttribute('aria-expanded', 'false');
  await page.screenshot({ path: fileURLToPath(new URL('sidebar-collapsed-icon.png', output)) });
  await toggle.click();
  await expect(toggle.locator('[data-icon="Fold"]')).toBeVisible();
  const translate = page.locator('.lang-btn [data-icon="Translate"] svg');
  await expect(translate).toHaveAttribute('viewBox', '0 0 24 24');
  await expect(translate.locator('path')).toHaveCount(2);
  await expect(translate.locator('path').first()).toHaveAttribute('stroke', 'currentColor');
  await expect(translate).toHaveAttribute('fill', 'none');
  await page.locator('.lang-btn').click();
  await page.getByRole('menuitem', { name: /English/ }).click();
  await expect(toggle).toHaveAttribute('aria-label', 'Collapse sidebar');
  await page.locator('.lang-btn').click();
  await page.getByRole('menuitem', { name: /中文/ }).click();
  await expect(toggle).toHaveAttribute('aria-label', '收起侧栏');
  await page.screenshot({ path: fileURLToPath(new URL('navigation-icons-fixed.png', output)) });
  report.checks.push('Sidebar icons alternate Fold/Expand, translation SVG is correct, and both languages work');
  await page.locator('.header-user-btn').click();
  await page.getByRole('menuitem', { name: '升级', exact: true }).click();
  await expect(page.getByText('HomeWaf 更新源尚未发布正式版本，发布后即可检查更新', { exact: true })).toBeVisible();
  await expect(page.locator('.el-dialog:visible')).toHaveCount(0);
  updateAvailable = true;
  await page.locator('.header-user-btn').click();
  await page.getByRole('menuitem', { name: '升级', exact: true }).click();
  await expect(page.locator('.el-dialog:visible')).toContainText('v2.0.1');
  report.checks.push('Empty release state shows an informational message; a newer release opens the update dialog');
  expect(report.errors).toEqual([]);
  fs.writeFileSync(new URL('update-theme-verification.json', output), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} catch (error) {
  console.error(JSON.stringify(report));
  await page.screenshot({ path: fileURLToPath(new URL('update-theme-failure.png', output)) });
  throw error;
} finally {
  await browser.close();
}
